export const PRODUCT_MESSAGES: Record<
  ProductLocale,
  Readonly<Record<ProductMessageKey, string>>
> = { en, fr, es };

export type ProductMessageValues = Record<string, string | number>;

export function translateProductMessage(
  locale: unknown,
  key: ProductMessageKey,
  values?: ProductMessageValues,
) {
  const normalizedLocale = normalizeProductLocale(locale);
  const template =
    PRODUCT_MESSAGES[normalizedLocale][key] ||
    PRODUCT_MESSAGES[DEFAULT_PRODUCT_LOCALE][key];

  if (!values) return template;

  return template.replace(/\{\{([a-zA-Z0-9_]+)\}\}/g, (match, token: string) => {
    const value = values[token];
    return value === undefined ? match : String(value);
  });
}

export function getMissingProductMessageKeys(locale: ProductLocale) {
  return (Object.keys(en) as ProductMessageKey[]).filter(
    (key) => !PRODUCT_MESSAGES[locale][key]?.trim(),
  );
}

export function getProductMessageKeys() {
  return Object.keys(en) as ProductMessageKey[];
}
