import { createHash } from "node:crypto";
import { createReadStream, createWriteStream } from "node:fs";
import { chmod, mkdir, readFile, rm, stat, writeFile } from "node:fs/promises";
import path from "node:path";
import { pipeline } from "node:stream/promises";
import { createGzip } from "node:zlib";
import { spawn } from "node:child_process";

const repoRoot = process.cwd();
const dockerBinDir = path.join(process.env.HOME ?? "", "Applications", "Docker.app", "Contents", "Resources", "bin");
if (process.env.HOME && !process.env.PATH?.split(path.delimiter).includes(dockerBinDir)) {
  process.env.PATH = `${dockerBinDir}${path.delimiter}${process.env.PATH ?? ""}`;
}

const backupAck = process.env.DEALFLOW_BACKUP_ACK;
const outputRoot = process.env.DEALFLOW_BACKUP_DIR ?? path.join(repoRoot, ".backups", "supabase");
const projectRef =
  process.env.SUPABASE_PROJECT_REF ??
  (await readOptionalText(path.join(repoRoot, "supabase", ".temp", "project-ref")))?.trim() ??
  "fdzwbevvbqvyteapphxm";

if (backupAck !== "production-data") {
  throw new Error(
    "Refusing to create a production data backup without DEALFLOW_BACKUP_ACK=production-data",
  );
}

await assertDockerAvailable();
await refreshLinkedPostgresVersion(projectRef);

const timestamp = new Date().toISOString().replaceAll(":", "").replace(/\.\d{3}Z$/, "Z");
const backupDir = path.join(outputRoot, `${projectRef}-${timestamp}`);

await mkdir(backupDir, { recursive: true, mode: 0o700 });
await chmod(outputRoot, 0o700).catch(() => undefined);
await chmod(backupDir, 0o700);

const parts = [
  {
    name: "roles",
    args: ["db", "dump", "--role-only", "--linked"],
  },
  {
    name: "schema",
    args: ["db", "dump", "--linked"],
  },
  {
    name: "data",
    args: ["db", "dump", "--data-only", "--linked"],
  },
];

const files = [];

for (const part of parts) {
  const sqlPath = path.join(backupDir, `${part.name}.sql`);
  const gzipPath = `${sqlPath}.gz`;

  await runSupabaseDump([...part.args, "--file", sqlPath]);
  await chmod(sqlPath, 0o600);
  await gzipFile(sqlPath, gzipPath);
  await chmod(gzipPath, 0o600);
  await rm(sqlPath, { force: true });

  const gzipStat = await stat(gzipPath);
  files.push({
    name: path.basename(gzipPath),
    bytes: gzipStat.size,
    sha256: await sha256File(gzipPath),
  });
}

const manifest = {
  created_at: new Date().toISOString(),
  project_ref: projectRef,
  backup_dir: backupDir,
  files,
  restore_order: ["roles.sql.gz", "schema.sql.gz", "data.sql.gz"],
  contains_sensitive_data: true,
  notes: [
    "Logical backup generated by Supabase CLI.",
    "Keep this directory encrypted or in a restricted-access backup destination.",
    "Do not commit backup artifacts.",
  ],
};

const manifestPath = path.join(backupDir, "manifest.json");
await writeFile(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`, { mode: 0o600 });
await chmod(manifestPath, 0o600);

console.log(JSON.stringify({ backupDir, files }, null, 2));

async function readOptionalText(filePath) {
  try {
    return await readFile(filePath, "utf8");
  } catch {
    return null;
  }
}

async function runSupabaseDump(args) {
  await new Promise((resolve, reject) => {
    const child = spawn("supabase", args, {
      cwd: repoRoot,
      env: process.env,
      stdio: ["ignore", "pipe", "pipe"],
    });

    let stderr = "";
    child.stdout.on("data", (chunk) => process.stdout.write(chunk));
    child.stderr.on("data", (chunk) => {
      stderr += chunk;
      process.stderr.write(chunk);
    });
    child.on("error", reject);
    child.on("close", (code) => {
      if (code === 0) {
        resolve();
        return;
      }

      reject(new Error(`supabase ${args.join(" ")} failed with exit code ${code}\n${stderr}`));
    });
  });
}

async function assertDockerAvailable() {
  await new Promise((resolve, reject) => {
    const child = spawn("docker", ["info"], {
      cwd: repoRoot,
      env: process.env,
      stdio: ["ignore", "ignore", "pipe"],
    });

    let stderr = "";
    child.stderr.on("data", (chunk) => {
      stderr += chunk;
    });
    child.on("error", () => {
      reject(new Error("Docker is required for Supabase CLI logical backups, but the docker command is unavailable."));
    });
    child.on("close", (code) => {
      if (code === 0) {
        resolve();
        return;
      }

      reject(
        new Error(
          `Docker is required for Supabase CLI logical backups, but Docker is not running or unavailable.\n${stderr}`,
        ),
      );
    });
  });
}

async function refreshLinkedPostgresVersion(ref) {
  const projects = await getSupabaseProjects();
  const project = projects.find((candidate) => candidate.ref === ref || candidate.id === ref);
  const version = project?.database?.version;

  if (!version) {
    return;
  }

  await mkdir(path.join(repoRoot, "supabase", ".temp"), { recursive: true });
  await writeFile(path.join(repoRoot, "supabase", ".temp", "postgres-version"), `${version}\n`);
}

async function getSupabaseProjects() {
  const stdout = await new Promise((resolve, reject) => {
    const child = spawn("supabase", ["projects", "list", "-o", "json"], {
      cwd: repoRoot,
      env: process.env,
      stdio: ["ignore", "pipe", "pipe"],
    });

    let output = "";
    let stderr = "";
    child.stdout.on("data", (chunk) => {
      output += chunk;
    });
    child.stderr.on("data", (chunk) => {
      stderr += chunk;
    });
    child.on("error", reject);
    child.on("close", (code) => {
      if (code === 0) {
        resolve(output);
        return;
      }

      reject(new Error(`supabase projects list failed with exit code ${code}\n${stderr}`));
    });
  });

  return JSON.parse(stdout);
}

async function gzipFile(sourcePath, targetPath) {
  await pipeline(createReadStream(sourcePath), createGzip({ level: 9 }), createWriteStream(targetPath));
}

async function sha256File(filePath) {
  const hash = createHash("sha256");
  for await (const chunk of createReadStream(filePath)) {
    hash.update(chunk);
  }
  return hash.digest("hex");
}
